/** 1-based index of an ARRL section, or -1. Matches the first three characters like the Fortran does. */
function arrlSectionIndex(word) {
  const key = (String(word) + '   ').slice(0, 3);
  for (let i = 0; i < NSEC; i++) {
    if ((ARRL_SECTIONS[i] + '   ').slice(0, 3) === key) return i + 1;
  }
  return -1;
}

