function makeAtom(fields) {
  return { kind: -1, subtype: 0, role: ROLE.FIELD_ONLY, value: 0, value2: 0, text: '', ...fields };
}
const callAtom = (action, call) => makeAtom({ kind: ATOM.CALL, subtype: action, text: call });
const exchNumAtom = (role, kind, value) => makeAtom({ kind: ATOM.EXCH_NUM, role, subtype: kind, value });
const exchLocAtom = (role, kind, token) => makeAtom({ kind: ATOM.EXCH_LOC, role, subtype: kind, text: token });
const zoneLocAtom = (zone, token) =>
  makeAtom({ kind: ATOM.EXCH_PAIR, subtype: PAIR_KIND.ZONE_LOC3, value: zone, text: token });
const classSectionAtom = (count, cls, sectionIndex) =>
  makeAtom({ kind: ATOM.EXCH_PAIR, subtype: PAIR_KIND.CLASS_SECTION, value: count, value2: sectionIndex, text: cls });
const exchNumTimeAtom = (role, serial, minuteOfDay) =>
  makeAtom({ kind: ATOM.EXCH_NUM_TIME, role, value: serial, value2: minuteOfDay });
const controlAtom = (phraseId) => makeAtom({ kind: ATOM.CONTROL, subtype: phraseId });
const grid4Atom = (role, grid) => makeAtom({ kind: ATOM.GRID4, role, text: grid });
const text5Atom = (text) => makeAtom({ kind: ATOM.TEXT5, text: text.slice(0, 5).padEnd(5, ' ') });

