const NTOKENS = 2063592;
const MAX22 = 4194304;
const C1 = ' 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ';
const C2 = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ';
const C3 = '0123456789';
const C4 = ' ABCDEFGHIJKLMNOPQRSTUVWXYZ';

const isDigit = (c) => c >= '0' && c <= '9';
const isLetter = (c) => c >= 'A' && c <= 'Z';

/** chkcall() restricted to the non-compound case (compound calls are rejected by JTTY anyway). */
function chkcall(w) {
  const n1 = w.length;
  if (n1 > 11 || /[.+\-?]/.test(w)) return false;
  if (n1 > 6) return false; // no '/' reaches here
  const bc = w.padEnd(6, ' ');
  const nbc = n1;
  if (!isLetter(bc[0]) && !isLetter(bc[1])) return false;
  if (bc[0] === 'Q' && bc.slice(0, 5) !== 'QU1RK') return false;
  let i1 = 0;
  if (isDigit(bc[1])) i1 = 2;
  if (isDigit(bc[2])) i1 = 3;
  if (i1 === 0 || i1 === nbc) return false;
  let n = 0;
  for (let i = i1; i < nbc; i++) {
    if (!isLetter(bc[i])) return false;
    n++;
  }
  return n >= 1 && n <= 3;
}

/** callok() from packjt77.f90: the post-unpack sanity check. */
function callok(w) {
  const n = w.length;
  if (n < 3 || w[0] === 'Q') return false;
  let i0 = 0;
  for (let i = n; i >= 1; i--) {
    if (isDigit(w[i - 1])) {
      i0 = i;
      break;
    }
  }
  if (i0 !== 2 && i0 !== 3) return false;
  const pfx = w.slice(0, i0 - 1);
  let nlp = 0;
  let ndp = 0;
  for (const c of pfx) {
    if (isDigit(c)) ndp++;
    if (isLetter(c) || (c >= 'a' && c <= 'z')) nlp++;
  }
  if (nlp + ndp !== pfx.length || nlp === 0) return false;
  const ns = n - i0;
  if (ns < 1 || ns > 3) return false;
  for (let i = i0; i < n; i++) if (!isLetter(w[i]) && !(w[i] >= 'a' && w[i] <= 'z')) return false;
  return true;
}

/** pack77_c28_standard_shape() from packjt77_grammar.f90. */
function c28StandardShape(token) {
  const n = token.length;
  if (n < 3 || n > 6) return false;
  for (const c of token) if (!isLetter(c) && !isDigit(c)) return false;
  let iarea = 0;
  for (let i = n; i >= 2; i--) {
    if (isDigit(token[i - 1])) {
      iarea = i;
      break;
    }
  }
  if (iarea !== 2 && iarea !== 3) return false;
  let npdig = 0;
  let nplet = 0;
  for (let i = 1; i < iarea; i++) {
    const c = token[i - 1];
    if (isDigit(c)) npdig++;
    else if (isLetter(c)) nplet++;
    else return false;
  }
  if (nplet === 0 || npdig >= iarea - 1) return false;
  let nslet = 0;
  for (let i = iarea + 1; i <= n; i++) {
    if (isLetter(token[i - 1])) nslet++;
    else return false;
  }
  return nslet <= 3;
}

/**
 * Packs a *standard* callsign into its 28-bit field; returns null for
 * anything that would not pack as a standard call (hash/special tokens are
 * deliberately not produced — JTTY call atoms only carry calls that
 * round-trip through the standard grammar).
 */
function pack28Standard(call) {
  if (!c28StandardShape(call)) return null;
  const n = call.length;
  let iarea = 1;
  for (let i = n; i >= 2; i--) {
    if (isDigit(call[i - 1])) {
      iarea = i;
      break;
    }
  }
  let cs;
  if (iarea === 2) cs = (' ' + call.slice(0, 5)).padEnd(6, ' ');
  else cs = call.slice(0, 6).padEnd(6, ' ');
  const i1 = C1.indexOf(cs[0]);
  const i2 = C2.indexOf(cs[1]);
  const i3 = C3.indexOf(cs[2]);
  const i4 = C4.indexOf(cs[3]);
  const i5 = C4.indexOf(cs[4]);
  const i6 = C4.indexOf(cs[5]);
  if (i1 < 0 || i2 < 0 || i3 < 0 || i4 < 0 || i5 < 0 || i6 < 0) return null;
  const v = 36 * 10 * 27 * 27 * 27 * i1 + 10 * 27 * 27 * 27 * i2 + 27 * 27 * 27 * i3 + 27 * 27 * i4 + 27 * i5 + i6;
  return (v + NTOKENS + MAX22) % 268435456;
}

/** Inverse of pack28Standard; null unless n28 is a valid standard callsign. */
function unpack28Standard(n28) {
  if (!Number.isInteger(n28) || n28 < NTOKENS + MAX22 || n28 >= 268435456) return null;
  let n = n28 - NTOKENS - MAX22;
  const i1 = Math.floor(n / (36 * 10 * 27 * 27 * 27));
  n -= 36 * 10 * 27 * 27 * 27 * i1;
  const i2 = Math.floor(n / (10 * 27 * 27 * 27));
  n -= 10 * 27 * 27 * 27 * i2;
  const i3 = Math.floor(n / (27 * 27 * 27));
  n -= 27 * 27 * 27 * i3;
  const i4 = Math.floor(n / (27 * 27));
  n -= 27 * 27 * i4;
  const i5 = Math.floor(n / 27);
  const i6 = n - 27 * i5;
  if (i1 > 36) return null;
  const c13 = (C1[i1] + C2[i2] + C3[i3] + C4[i4] + C4[i5] + C4[i6]).replace(/^ +/, '').replace(/ +$/, '');
  if (!callok(c13)) return null;
  // An embedded space (a gap inside the call) is invalid.
  if (c13.includes(' ')) return null;
  return c13;
}

/** standard_call() from jtty_source_codec.f90. */
function standardCall(text) {
  const work = String(text).trim();
  if (work.length === 0 || work.includes('/')) return false;
  if (!chkcall(work) || work[0] === 'Q') return false;
  if (!/^[A-Z0-9]+$/.test(work)) return false;
  const n28 = pack28Standard(work);
  if (n28 === null) return false;
  return unpack28Standard(n28) === work;
}

