const finishStruct = (body, family) => 4 * (8 * body + family) + 2;

/**
 * Packs one atom into a 34-character '0'/'1' frame string (32 grammar bits,
 * reserved-zero bit 33, EOM bit 34), or returns null if the atom is invalid.
 */
function packAtom(atom, eom) {
  let n32;
  switch (atom.kind) {
    case ATOM.CALL: {
      if (!(atom.subtype >= 0 && atom.subtype <= 5)) return null;
      if (!standardCall(atom.text)) return null;
      const n28 = pack28Standard(atom.text);
      if (n28 === null || unpack28Standard(n28) !== atom.text) return null;
      let i2;
      let n2;
      if (atom.subtype <= 3) {
        i2 = 0;
        n2 = atom.subtype;
      } else {
        i2 = 1;
        n2 = atom.subtype - 4;
      }
      n32 = n28 * 16 + 4 * n2 + i2;
      break;
    }
    case ATOM.EXCH_NUM: {
      if (!validRole(atom.role) || !validNumber(atom.subtype, atom.value)) return null;
      const body = atom.role * 2 ** 26 + atom.subtype * 2 ** 22 + atom.value * 32;
      n32 = finishStruct(body, 0);
      break;
    }
    case ATOM.EXCH_LOC: {
      if (!validRole(atom.role) || !(atom.subtype >= 0 && atom.subtype <= 4)) return null;
      const n = atom.text.length;
      if (n !== 2 && n !== 3) return null;
      const token = packBase36(atom.text);
      if (token === null) return null;
      const body = atom.role * 2 ** 26 + atom.subtype * 2 ** 22 + (n - 2) * 2 ** 21 + token * 32;
      n32 = finishStruct(body, 1);
      break;
    }
    case ATOM.EXCH_PAIR: {
      let pairData;
      if (atom.subtype === PAIR_KIND.ZONE_LOC3) {
        if (!(atom.value >= 1 && atom.value <= 40)) return null;
        const n = atom.text.length;
        if (n !== 2 && n !== 3) return null;
        const token = packBase36(atom.text);
        if (token === null) return null;
        pairData = atom.value * 2 ** 17 + (n - 2) * 2 ** 16 + token;
      } else if (atom.subtype === PAIR_KIND.CLASS_SECTION) {
        if (!(atom.value >= 1 && atom.value <= 32)) return null;
        if (!(atom.value2 >= 1 && atom.value2 <= NSEC) || atom.text.length !== 1) return null;
        const cls = atom.text.charCodeAt(0) - 65;
        if (cls < 0 || cls > 5) return null;
        pairData = atom.value * 2 ** 17 + cls * 2 ** 14 + atom.value2 * 128;
      } else {
        return null;
      }
      const body = atom.subtype * 2 ** 24 + pairData * 2;
      n32 = finishStruct(body, 2);
      break;
    }
    case ATOM.EXCH_NUM_TIME: {
      if (!validRole(atom.role) || !(atom.value >= 0 && atom.value <= 16383)) return null;
      if (!(atom.value2 >= 0 && atom.value2 <= 1439)) return null;
      const body = atom.role * 2 ** 26 + atom.value * 2 ** 12 + atom.value2 * 2;
      n32 = finishStruct(body, 3);
      break;
    }
    case ATOM.CONTROL: {
      if (!(atom.subtype >= 0 && atom.subtype <= 17)) return null;
      const body = 0 * 2 ** 23 + atom.subtype * 2 ** 16;
      n32 = finishStruct(body, 4);
      break;
    }
    case ATOM.GRID4: {
      if (!validRole(atom.role)) return null;
      const idx = grid4ToIndex(atom.text);
      if (idx === null) return null;
      const data = atom.role * 2 ** 22 + idx * 128;
      const body = 1 * 2 ** 23 + data;
      n32 = finishStruct(body, 4);
      break;
    }
    case ATOM.TEXT5: {
      const t = atom.text.slice(0, 5).padEnd(5, ' ');
      let top30 = 0;
      for (const c of t) {
        const idx = ALPHABET.indexOf(c);
        if (idx < 0) return null;
        top30 = 64 * top30 + idx;
      }
      n32 = 4 * top30 + 3;
      break;
    }
    default:
      return null;
  }
  return n32.toString(2).padStart(32, '0') + '0' + (eom ? '1' : '0');
}

const ibits = (v, pos, len) => Math.floor(v / 2 ** pos) % 2 ** len;

/** Unpacks one 34-character frame. Returns {valid, atom, eom}. */
function unpackAtom(frame) {
  const bad = { valid: false, atom: makeAtom({}), eom: false };
  if (typeof frame !== 'string' || frame.length !== 34 || !/^[01]+$/.test(frame) || frame[32] !== '0') return bad;
  if (/^0{32}/.test(frame)) return bad;
  const top30 = parseInt(frame.slice(0, 30), 2);
  const i2 = parseInt(frame.slice(30, 32), 2);
  let atom;
  if (i2 === 0 || i2 === 1) {
    const n28 = parseInt(frame.slice(0, 28), 2);
    const n2 = parseInt(frame.slice(28, 30), 2);
    if (i2 === 1 && n2 > 1) return bad;
    const call = unpack28Standard(n28);
    if (call === null || !standardCall(call)) return bad;
    atom = callAtom(i2 === 0 ? n2 : n2 + 4, call);
  } else if (i2 === 2) {
    const family = top30 % 8;
    const body = Math.floor(top30 / 8);
    switch (family) {
      case 0: {
        const role = ibits(body, 26, 1);
        const subtype = ibits(body, 22, 4);
        const value = ibits(body, 5, 17);
        if (ibits(body, 0, 5) !== 0 || !validNumber(subtype, value)) return bad;
        atom = exchNumAtom(role, subtype, value);
        break;
      }
      case 1: {
        const role = ibits(body, 26, 1);
        const subtype = ibits(body, 22, 4);
        const n = ibits(body, 21, 1) + 2;
        const token = ibits(body, 5, 16);
        if (ibits(body, 0, 5) !== 0 || subtype > 4 || token >= 36 ** n) return bad;
        if (n === 3 && token < 36 ** 2) return bad;
        atom = exchLocAtom(role, subtype, unpackBase36(token, n));
        break;
      }
      case 2: {
        const subtype = ibits(body, 24, 3);
        const pair = ibits(body, 1, 23);
        if (ibits(body, 0, 1) !== 0) return bad;
        if (subtype === PAIR_KIND.ZONE_LOC3) {
          const value = ibits(pair, 17, 6);
          const n = ibits(pair, 16, 1) + 2;
          const token = ibits(pair, 0, 16);
          if (value < 1 || value > 40 || token >= 36 ** n) return bad;
          if (n === 3 && token < 36 ** 2) return bad;
          atom = zoneLocAtom(value, unpackBase36(token, n));
        } else if (subtype === PAIR_KIND.CLASS_SECTION) {
          const value = ibits(pair, 17, 6);
          const cls = ibits(pair, 14, 3);
          const value2 = ibits(pair, 7, 7);
          if (value < 1 || value > 32 || cls > 5) return bad;
          if (value2 < 1 || value2 > NSEC || ibits(pair, 0, 7) !== 0) return bad;
          atom = classSectionAtom(value, String.fromCharCode(65 + cls), value2);
        } else {
          return bad;
        }
        break;
      }
      case 3: {
        const role = ibits(body, 26, 1);
        const value = ibits(body, 12, 14);
        const value2 = ibits(body, 1, 11);
        if (ibits(body, 0, 1) !== 0 || value2 > 1439) return bad;
        atom = exchNumTimeAtom(role, value, value2);
        break;
      }
      case 4: {
        const kind = ibits(body, 23, 4);
        const data = ibits(body, 0, 23);
        if (kind === 0) {
          const subtype = ibits(data, 16, 7);
          if (ibits(data, 0, 16) !== 0 || subtype > 17) return bad;
          atom = controlAtom(subtype);
        } else if (kind === 1) {
          const role = ibits(data, 22, 1);
          const idx = ibits(data, 7, 15);
          if (ibits(data, 0, 7) !== 0 || idx >= 32400) return bad;
          atom = grid4Atom(role, indexToGrid4(idx));
        } else {
          return bad;
        }
        break;
      }
      default:
        return bad;
    }
  } else {
    let text = '';
    for (let i = 1; i <= 5; i++) text += ALPHABET[ibits(top30, 6 * (5 - i), 6)];
    atom = makeAtom({ kind: ATOM.TEXT5, text });
  }
  return { valid: true, atom, eom: frame[33] === '1' };
}

function renderRole(role, field) {
  return role === ROLE.FULL ? `599 ${field}` : field;
}

function renderNumber(kind, value) {
  switch (kind) {
    case NUM_KIND.SERIAL:
      return value < 1000 ? pad(value, 3) : String(value);
    case NUM_KIND.CQ_ZONE:
    case NUM_KIND.ITU_ZONE:
    case NUM_KIND.CHECK:
      return value < 100 ? pad(value, 2) : String(value);
    case NUM_KIND.LICENSE_YEAR:
      return pad(value, 4);
    default:
      return String(value);
  }
}

/** Canonical on-screen rendering of one atom (no trailing separator), or null if invalid. */
function renderAtom(atom) {
  switch (atom.kind) {
    case ATOM.CALL:
      switch (atom.subtype) {
        case CALL_ACTION.CQ:
          return `CQ ${atom.text} CQ`;
        case CALL_ACTION.CALL:
          return atom.text;
        case CALL_ACTION.TU_CQ:
          return `TU ${atom.text} CQ`;
        case CALL_ACTION.CALL_TU:
          return `${atom.text} TU`;
        case CALL_ACTION.CALL_AGN:
          return `${atom.text} AGN?`;
        case CALL_ACTION.TU_NOW:
          return `TU NOW ${atom.text}`;
        default:
          return null;
      }
    case ATOM.EXCH_NUM:
      if (!validRole(atom.role) || !validNumber(atom.subtype, atom.value)) return null;
      return renderRole(atom.role, renderNumber(atom.subtype, atom.value));
    case ATOM.EXCH_LOC:
      if (atom.subtype < 0 || atom.subtype > 4) return null;
      return renderRole(atom.role, atom.text);
    case ATOM.EXCH_PAIR:
      if (atom.subtype === PAIR_KIND.ZONE_LOC3) return `599 ${pad(atom.value, 2)} ${atom.text}`;
      if (atom.subtype === PAIR_KIND.CLASS_SECTION) {
        if (atom.value2 < 1 || atom.value2 > NSEC) return null;
        return `${atom.value}${atom.text[0]} ${ARRL_SECTIONS[atom.value2 - 1]}`;
      }
      return null;
    case ATOM.EXCH_NUM_TIME: {
      if (!validRole(atom.role) || atom.value < 0 || atom.value > 16383) return null;
      if (atom.value2 < 0 || atom.value2 > 1439) return null;
      const hhmm = pad(Math.floor(atom.value2 / 60), 2) + pad(atom.value2 % 60, 2);
      return renderRole(atom.role, `${renderNumber(NUM_KIND.SERIAL, atom.value)} ${hhmm}`);
    }
    case ATOM.CONTROL:
      if (atom.subtype < 0 || atom.subtype > 17) return null;
      return CONTROL_TEXT[atom.subtype];
    case ATOM.GRID4:
      return renderRole(atom.role, atom.text.slice(0, 4));
    case ATOM.TEXT5:
      return atom.text.slice(0, 5);
    default:
      return null;
  }
}

/** pack_jtty_atoms(): atoms -> frames (EOM set only on the last unless isFinal is false). Returns null if any atom is invalid. */
function packAtoms(atoms, isFinal = true) {
  if (atoms.length < 1 || atoms.length > MAX_FRAMES) return null;
  const frames = [];
  for (let i = 0; i < atoms.length; i++) {
    const frame = packAtom(atoms[i], i === atoms.length - 1 && isFinal);
    if (frame === null) return null;
    frames.push(frame);
  }
  return frames;
}

