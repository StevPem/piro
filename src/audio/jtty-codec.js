function packBase36(token) {
  if (token.length !== 2 && token.length !== 3) return null;
  let value = 0;
  for (const c of token) {
    const d = BASE36.indexOf(c);
    if (d < 0) return null;
    value = 36 * value + d;
  }
  if (token.length === 3 && value < 36 * 36) return null;
  return value;
}

function unpackBase36(value, n) {
  let work = value;
  let out = '';
  for (let i = 0; i < n; i++) {
    out = BASE36[work % 36] + out;
    work = Math.floor(work / 36);
  }
  return out;
}

function grid4ToIndex(grid) {
  if (grid.length !== 4) return null;
  const a = grid.charCodeAt(0) - 65;
  const b = grid.charCodeAt(1) - 65;
  const c = grid.charCodeAt(2) - 48;
  const d = grid.charCodeAt(3) - 48;
  if (a < 0 || a >= 18 || b < 0 || b >= 18 || c < 0 || c >= 10 || d < 0 || d >= 10) return null;
  return ((a * 18 + b) * 10 + c) * 10 + d;
}

function indexToGrid4(index) {
  let work = index;
  const d = work % 10;
  work = Math.floor(work / 10);
  const c = work % 10;
  work = Math.floor(work / 10);
  const b = work % 18;
  const a = Math.floor(work / 18);
  return String.fromCharCode(65 + a, 65 + b, 48 + c, 48 + d);
}

const validRole = (role) => role === ROLE.FIELD_ONLY || role === ROLE.FULL;

function validNumber(kind, value) {
  if (!(kind >= 0 && kind <= 7 && Number.isInteger(value) && value >= 0 && value <= 131071)) return false;
  if (kind === NUM_KIND.CQ_ZONE) return value >= 1 && value <= 40;
  if (kind === NUM_KIND.ITU_ZONE) return value >= 1 && value <= 90;
  if (kind === NUM_KIND.LICENSE_YEAR) return value <= 9999;
  return true;
}

const pad = (v, w) => String(v).padStart(w, '0');

/** Parses a canonical-length decimal token (1-6 digits, 0..131071), like decimal_value(). */
function decimalValue(text) {
  if (text.length < 1 || text.length > 6 || !/^[0-9]+$/.test(text)) return null;
  const v = parseInt(text, 10);
  return v <= 131071 ? v : null;
}

