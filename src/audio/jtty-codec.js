/** normalize_jtty_message(): fold operator text into the source alphabet. */
function normalizeMessage(raw) {
  let out = '';
  let lastSpace = true;
  const input = String(raw).slice(0, MAX_MESSAGE_CHARS);
  for (let ch of input) {
    if (ch === '\0' || ch === '~') ch = ' ';
    if (ch >= 'a' && ch <= 'z') ch = ch.toUpperCase();
    if (ALPHABET.indexOf(ch) < 0 || ch.length !== 1) ch = '#';
    if (ch === ' ') {
      if (lastSpace) continue;
      out += ' ';
      lastSpace = true;
    } else {
      out += ch;
      lastSpace = false;
    }
  }
  return out.replace(/ +$/, '');
}

/** RTTY Roundup: canonicalize decimal tokens that follow a complete "599" to the SERIAL spelling. */
function normalizeSerials(msg) {
  const words = msg.split(' ');
  const out = [];
  for (let i = 0; i < words.length; i++) {
    let rendered = words[i];
    if (rendered === '599' && i + 1 < words.length) {
      const value = decimalValue(words[i + 1]);
      if (value !== null) {
        rendered = renderAtom(exchNumAtom(ROLE.FULL, NUM_KIND.SERIAL, value));
        i++;
      }
    }
    out.push(rendered);
    if (out.join(' ').length > MAX_MESSAGE_CHARS) return null;
  }
  return out.join(' ');
}

/**
 * Packs operator text into the minimum number of 34-bit frames.
 *
 * @param {string} text
 * @param {object} [opts]
 * @param {'unknown'|'field-day'|'rtty-roundup'} [opts.profile='unknown']
 * @param {boolean} [opts.isFinal=true] - false suppresses EOM on the last frame
 * @returns {{message: string, atoms: object[], frames: string[], nframes: number}}
 *   nframes is 0 for empty text and -1 if the text cannot be encoded (over 16 frames, or an RTTY-Roundup normalization overflow).
 */
function packText(text, opts = {}) {
  const profile = opts.profile ?? PROFILE.UNKNOWN;
  const isFinal = opts.isFinal ?? true;
  if (profile !== PROFILE.UNKNOWN && profile !== PROFILE.FIELD_DAY && profile !== PROFILE.RTTY_ROUNDUP) {
    return { message: '', atoms: [], frames: [], nframes: -1 };
  }
  let msg = normalizeMessage(text);
  if (profile === PROFILE.RTTY_ROUNDUP) {
    const normalized = normalizeSerials(msg);
    if (normalized === null) return { message: msg, atoms: [], frames: [], nframes: -1 };
    msg = normalized;
  }
  const n = msg.length;
  if (n <= 0) return { message: msg, atoms: [], frames: [], nframes: 0 };

  const INF = 999;
  // 1-based, mirroring the Fortran: dp[i] = minimum frames for msg(i:n).
  const dp = new Array(n + 2).fill(INF);
  const successor = new Array(n + 2).fill(0);
  const choice = new Array(n + 2).fill(null);
  dp[n + 1] = 0;
  const at = (i) => msg[i - 1];
  const span = (a, b) => msg.slice(a - 1, b); // msg(a:b)

  let ipos = n;

  function consider(atom, next) {
    const cost = 1 + dp[next];
    if (cost > MAX_FRAMES || cost > dp[ipos]) return;
    const rank = atom.kind === ATOM.TEXT5 ? 1 : 0;
    const cur = choice[ipos];
    const bestRank = cur && cur.kind === ATOM.TEXT5 ? 1 : 0;
    const key = 100 * atom.kind + 2 * atom.subtype + atom.role;
    const bestKey = cur ? 100 * cur.kind + 2 * cur.subtype + cur.role : 100 * -1;
    if (cost === dp[ipos]) {
      if (rank > bestRank) return;
      if (rank === bestRank) {
        if (next < successor[ipos]) return;
        if (next === successor[ipos] && key >= bestKey) return;
      }
    }
    dp[ipos] = cost;
    successor[ipos] = next;
    choice[ipos] = atom;
  }

  // offer(): validate a candidate exactly as the reference does — pack it,
  // unpack it, render it, and require it to match its span of the text.
  function offer(atom) {
    const frame = packAtom(atom, false);
    if (frame === null) return;
    const un = unpackAtom(frame);
    if (!un.valid) return;
    const rendered = renderAtom(un.atom);
    if (rendered === null || rendered.length === 0) return;
    const last = ipos + rendered.length - 1;
    if (last > n) return;
    if (span(ipos, last) !== rendered) return;
    let next = n + 1;
    if (last < n) {
      if (at(last + 1) !== ' ') return;
      next = last + 2; // structured frames supply exactly one following separator column
    }
    consider(atom, next);
  }

  function tryCompact() {
    const words = msg.slice(ipos - 1).split(' ').slice(0, 3);
    const nwords = words.length;

    for (let j = 0; j < nwords; j++) {
      if (words[j].length > 13) continue;
      for (let action = CALL_ACTION.CQ; action <= CALL_ACTION.TU_NOW; action++) offer(callAtom(action, words[j]));
    }
    for (let j = 0; j < CONTROL_TEXT.length; j++) offer(controlAtom(j));

    for (let role = ROLE.FIELD_ONLY; role <= ROLE.FULL; role++) {
      let field = 0;
      if (role === ROLE.FULL) {
        if (words[0] !== '599' || nwords < 2) continue;
        field = 1;
      }
      const word = words[field];
      const length = word.length;
      const value = decimalValue(word);
      if (value !== null) offer(exchNumAtom(role, NUM_KIND.GENERIC, value));
      if (value !== null && role === ROLE.FULL && profile === PROFILE.RTTY_ROUNDUP) {
        offer(exchNumAtom(role, NUM_KIND.SERIAL, value));
      }
      if (length === 4) offer(grid4Atom(role, word.slice(0, 4)));
      if (role !== ROLE.FULL || length < 2 || length > 3) continue;
      if (!/[A-Z]/.test(word)) continue;
      offer(exchLocAtom(role, LOC_KIND.QTH, word));
      if (profile === PROFILE.RTTY_ROUNDUP) offer(exchLocAtom(role, LOC_KIND.STATE_PROVINCE, word));
    }

    const length = words[0].length;
    if (nwords < 2 || length < 2 || length > 3) return;
    const count = decimalValue(words[0].slice(0, length - 1));
    if (count === null) return;
    const sectionIndex = arrlSectionIndex(words[1]);
    offer(classSectionAtom(count, words[0][length - 1], sectionIndex));
  }

  for (ipos = n; ipos >= 1; ipos--) {
    const inext = Math.min(n + 1, ipos + 5);
    consider(text5Atom(span(ipos, inext - 1)), inext);
    if (ipos > 1 && at(ipos - 1) !== ' ') continue;
    tryCompact();
  }

  if (dp[1] > MAX_FRAMES) return { message: msg, atoms: [], frames: [], nframes: -1 };
  const atoms = [];
  for (let p = 1; p <= n; p = successor[p]) atoms.push(choice[p]);
  const frames = packAtoms(atoms, isFinal);
  if (frames === null) return { message: msg, atoms: [], frames: [], nframes: -1 };
  return { message: msg, atoms, frames, nframes: frames.length };
}

/**
 * Turns a sequence of frames back into display text, as unpack_jtty() does.
 * `~` stands for a TEXT5 space (the reference decoder's display marker).
 */
function unpackFrames(frames) {
  let message = '';
  let valid = frames.length >= 1 && frames.length <= MAX_FRAMES;
  let lastEom = false;
  for (const frame of frames) {
    const un = unpackAtom(frame);
    if (!un.valid) {
      valid = false;
      lastEom = false;
      continue;
    }
    const rendered = renderAtom(un.atom);
    if (rendered === null) {
      valid = false;
      lastEom = false;
      continue;
    }
    lastEom = un.eom;
    if (un.atom.kind === ATOM.TEXT5) message += rendered.replace(/ /g, '~');
    else message += rendered + ' ';
  }
  return { message: message.slice(0, MAX_MESSAGE_CHARS), valid, isLastFrame: lastEom && valid };
}

